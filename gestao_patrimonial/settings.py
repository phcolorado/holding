def upload_documento(instance, filename):
    imovel_id = getattr(instance.imovel, 'pk', 'sem_imovel') if instance.imovel else 'sem_imovel'
    tipo = instance.tipo or 'outro'
    return f'documentos/imovel_{imovel_id}/{tipo}/{filename}'
